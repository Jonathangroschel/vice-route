export const ORDEM = new Map(CATEGORIAS.map((c, i) => [c.id, i + 1]))

/** "kind|type" → categoria e conjunto. */
export const POR_TIPO = new Map<string, { categoria: DefCategoria; conjunto?: string }>()
for (const c of CATEGORIAS) {
  for (const t of c.tipos)
    POR_TIPO.set(t, { categoria: c, conjunto: c.conjuntos?.find((x) => x.tipo === t)?.id })
}
